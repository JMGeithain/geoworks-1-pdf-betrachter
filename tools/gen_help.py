# tools/help_de.txt -> app/helptext.inc (GEOS 1 character set = Mac Roman)
import os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
out = ['; generated by tools/gen_help.py from tools/help_de.txt', 'help_text:']
for line in open(os.path.join(root, 'tools', 'help_de.txt'), encoding='utf-8'):
    line = line.rstrip('\n')
    if line.startswith('#'): continue
    if line.strip() == '':
        kind, text = 'E', ''
    else:
        kind, text = line[0], line[2:]
        assert kind in 'HTBS', line
        if kind == 'H': text = text.upper()
    b = text.encode('mac_roman')
    assert len(b) < 120, line
    out.append(' db %d%s,0' % (ord(kind), ''.join(',%d' % c for c in b)))
out.append(' db 0')
open(os.path.join(root, 'app', 'helptext.inc'), 'w').write('\n'.join(out) + '\n')
print(len(out) - 3, 'Zeilen')
