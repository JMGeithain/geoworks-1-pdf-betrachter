# Generates core/pdftabs.h: standard-14 widths, encodings, glyph names, Unicode->GEOS map.
import codecs
from reportlab.pdfbase import _fontdata as fd
from reportlab.pdfbase.pdfmetrics import getFont
out=[]
def arr(name,typ,vals,per=16):
    out.append("static const %s %s[%d] = {"%(typ,name,len(vals)))
    for i in range(0,len(vals),per):
        out.append("  "+",".join(str(v) for v in vals[i:i+per])+",")
    out.append("};")
# Standard encoding names -> unicode via reportlab glyph list
from reportlab.pdfbase._glyphlist import _glyphname2unicode as g2u
std = fd.encodings['StandardEncoding']
win = fd.encodings['WinAnsiEncoding']
mac = fd.encodings['MacRomanEncoding']
def enc_uni(enc):
    r=[]
    for n in enc:
        r.append(g2u.get(n,0) if n else 0)
    return r
# Unicode -> GEOS (Mac Roman) byte
def geos(u):
    if u==0: return 0
    if 32<=u<127: return u
    try:
        b=chr(u).encode('mac_roman')
        return b[0]
    except Exception: pass
    fall={0x2212:ord('-'),0xA0:32,0x2010:ord('-'),0x2011:ord('-'),0x2002:32,0x2003:32,0x2009:32,0xAD:ord('-'),0x2032:ord("'"),0x2033:ord('"')}
    return fall.get(u,ord('?'))
# widths for the standard fonts, indexed by StandardEncoding code (we index by glyph name ->unicode instead)
fonts=['Helvetica','Helvetica-Bold','Times-Roman','Times-Bold','Times-Italic','Times-BoldItalic']
# Build widths by GEOS char code (0..255) so the core can look up width after mapping
for f in fonts:
    w=fd.widthsByFontGlyph[f]
    tab=[0]*256
    for name,wd in w.items():
        u=g2u.get(name)
        if u is None: continue
        if isinstance(u,(list,tuple)): u=u[0]
        g=geos(u)
        if g and g!=ord('?') and tab[g]==0: tab[g]=wd
    tab[ord('?')]=w.get('question',500)
    for i in range(256):
        if tab[i]==0: tab[i]=w.get('space',250) if i<32 else 500
    arr("W_"+f.replace('-','_'),"unsigned short",tab)
def uni(enc):
    r=[]
    for n in enc:
        u=g2u.get(n,0) if n else 0
        if isinstance(u,(list,tuple)): u=u[0]
        r.append(u)
    return r
arr("ENC_STD","unsigned short",uni(std))
arr("ENC_WIN","unsigned short",uni(win))
arr("ENC_MAC","unsigned short",uni(mac))
# Unicode -> GEOS for U+00A0..U+00FF and a few others (pairs)
tbl=[geos(u) for u in range(0xA0,0x100)]
arr("U_A0_TO_GEOS","unsigned char",tbl)
extra=sorted({u for u in list(range(0x100,0x180))+[0x131,0x152,0x153,0x178,0x192,0x2C6,0x2DC,0x2013,0x2014,0x2018,0x2019,0x201A,0x201C,0x201D,0x201E,0x2020,0x2021,0x2022,0x2026,0x2030,0x2039,0x203A,0x20AC,0x2122,0x2212,0x2010,0x2011,0x2002,0x2003,0x2009,0xFB01,0xFB02,0x2032,0x2033,0x221E,0x2260,0x2264,0x2265,0x03C0,0x2211,0x220F,0x222B,0x2202,0x2206,0x221A,0x2248,0x25CA,0x03A9,0x00B5]})
pairs=[(u,geos(u)) for u in extra if geos(u)!=ord('?')]
# latin extended fallback: strip accents
import unicodedata
for u in range(0x100,0x180):
    if u in dict(pairs): continue
    base=unicodedata.normalize('NFD',chr(u))[0]
    if ord(base)<128: pairs.append((u,ord(base)))
pairs.sort()
arr("UX_KEY","unsigned short",[p[0] for p in pairs])
arr("UX_VAL","unsigned char",[p[1] for p in pairs])
# glyph names for Differences: all names in the three encodings + common extras
names=sorted({n for e in (std,win,mac) for n in e if n} | {'uni00E4','germandbls','Euro','minus','fi','fl','nbspace','sfthyphen','dotlessi'})
names=[n for n in names if not n.startswith('uni')]
nm=[];nv=[]
for n in names:
    u=g2u.get(n)
    if u is None: continue
    if isinstance(u,(list,tuple)): u=u[0]
    nm.append(n);nv.append(u)
out.append("static const char GN_STR[] =")
blob=""
offs=[]
for n in nm:
    offs.append(len(blob)); blob+=n+"\\0" if False else n+"\0"
# one literal per name, so no escape is split
line="  "
for n in nm:
    piece='"%s\\0"'%n
    if len(line)+len(piece)>76: out.append(line); line="  "
    line+=piece
out.append(line)
out.append(";")
arr("GN_OFF","unsigned short",offs)
arr("GN_UNI","unsigned short",nv)
out.append("#define GN_COUNT %d"%len(nm))
out.append("#define UX_COUNT %d"%len(pairs))
open('core/pdftabs.h','w').write("/* Generated by tools/gen_tables.py - do not edit. */\n"+"\n".join(out)+"\n")
print(len(nm),"glyph names,",len(pairs),"extra pairs")
